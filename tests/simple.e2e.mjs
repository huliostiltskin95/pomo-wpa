import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true});
try {
  const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8123/');
  await page.waitForFunction(() => typeof document.querySelector('[data-page="sessions"]')?.onclick === 'function', null, {timeout: 15000});
  await page.getByRole('button',{name:'Pianifica',exact:true}).click();
  await page.getByRole('button',{name:/Nuova sessione/}).click();
  await page.locator('#quick-date').fill('2099-11-06');
  await page.locator('summary').filter({hasText:'Incolla più sessioni'}).click();
  await page.locator('#quick').fill('Studio @45m +08:30');
  await page.locator('#planner-import').click();
  await page.locator('#prepare-plan').click();
  assert.match(await page.locator('#proposal-list').innerText(),/Studio/);
  await page.locator('#confirm-plan').click();
  await page.locator('#session-date').fill('2099-11-06');
  assert.match(await page.locator('#session-list').innerText(),/Studio/);
  await page.getByRole('button',{name:'Timer',exact:true}).click();
  await page.locator('#instant-minutes').fill('45');
  await page.locator('#instant-focus').fill('25');
  assert.match(await page.locator('#instant-end-time').innerText(),/\d{2}:\d{2}/);
  await page.getByRole('button',{name:'Inizia ora',exact:true}).click();
  assert.equal(await page.locator('#session-deadline').isVisible(),true);
  assert.equal(await page.getByRole('button',{name:'Pausa',exact:true}).isVisible(),true);
  await page.getByRole('button',{name:'Pausa',exact:true}).click();
  await page.getByRole('button',{name:'Riprendi',exact:true}).click();
  await page.getByRole('button',{name:'Concludi',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Inizia ora',exact:true}).isVisible(),true);
  await page.reload();
  const archive=await page.evaluate(()=>JSON.parse(localStorage.getItem('tempo-pomodoro-v2')));
  assert.ok(archive.sessions.some(s=>s.date==='2099-11-06'));
  assert.ok(archive.sessions.some(s=>s.finished));
  assert.deepEqual(errors,[]);
} finally { await browser.close(); }

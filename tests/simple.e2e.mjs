import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8123/');
 await page.getByRole('button',{name:'Sessioni',exact:true}).click();
 await page.locator('#window-date').fill('2099-11-06');
 await page.getByRole('button',{name:'Aggiungi fascia'}).click();
 await page.locator('#quick-focus').fill('35');
 await page.getByLabel('Una sessione per riga').fill('Studio @2h ~40m\nLavoro @45m');
 await page.getByRole('button',{name:'Prepara programma'}).click();
 assert.match(await page.locator('#proposal-list').innerText(),/09:00–11:00/);
 assert.match(await page.locator('#proposal-list').innerText(),/40 min focus/);
 assert.match(await page.locator('#proposal-list').innerText(),/35 min focus/);
 await page.getByRole('button',{name:'Conferma programma'}).click();
 await page.locator('#session-date').fill('2099-11-06');
 assert.match(await page.locator('#session-list').innerText(),/11:00–11:45/);
 await page.getByRole('button',{name:'Impostazioni',exact:true}).click();
 await page.getByLabel('Descrizione Markdown').fill('## Latino\n[Apri nota](obsidian://open?vault=Archivio&file=Latino)\n- [ ] Ripasso');
 await page.locator('#area-color').fill('#237ab0');
 await page.getByRole('button',{name:'Salva area'}).click();
 await page.getByRole('button',{name:'Chiudi',exact:true}).click();
 await page.getByRole('button',{name:'Timer',exact:true}).click();
 await page.locator('#resources summary').click();
 assert.equal(await page.getByRole('link',{name:'Apri nota'}).getAttribute('href'),'obsidian://open?vault=Archivio&file=Latino');
 await page.getByRole('checkbox',{name:'Ripasso'}).check();
 await page.reload();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('tempo-pomodoro-v2')).defaults.simple.areas.find(a=>a.name==='Studio').color),'#237AB0');
 await page.locator('#resources summary').click();
 assert.equal(await page.getByRole('checkbox',{name:'Ripasso'}).isChecked(),true);
 await page.locator('#instant-minutes').fill('45');
 const previewEnd=await page.locator('#instant-end-time').innerText();
 assert.match(previewEnd,/\\d{2}:\\d{2}/);
 assert.match(await page.locator('#instant-end-note').innerText(),/45 min lordi/);
 await page.locator('#instant-focus').fill('50');
 assert.match(await page.locator('#instant-pause-preview').innerText(),/10 min pausa/);
 await page.getByRole('button',{name:'Inizia ora',exact:true}).click();
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('tempo-pomodoro-v2')).sessions.at(-1).workMinutes),50);
 assert.equal(await page.locator('#session-deadline').isVisible(),true);
 assert.match(await page.locator('#deadline-detail').innerText(),/Tempo lordo residuo/);
 const storedTime=await page.evaluate(()=>{
   const session=JSON.parse(localStorage.getItem('tempo-pomodoro-v2')).sessions.at(-1);
   return new Intl.DateTimeFormat('it-IT',{hour:'2-digit',minute:'2-digit'}).format(new Date(session.timerEndsAt));
 });
 assert.equal((await page.locator('#deadline-time').innerText()).startsWith(storedTime),true);
 const beforePause=await page.locator('#deadline-time').innerText();
 await page.getByRole('button',{name:'Schermo intero'}).click();
 assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('focus-immersive')),true);
 assert.equal(await page.locator('#session-deadline').isVisible(),true);
 await page.getByRole('button',{name:'Esci da schermo intero'}).click();
 assert.equal(await page.locator('body').evaluate(el=>el.classList.contains('focus-immersive')),false);
 await page.getByRole('button',{name:'Pausa',exact:true}).click();
 assert.equal(await page.locator('#deadline-time').innerText(),beforePause);
 assert.match(await page.locator('#deadline-detail').innerText(),/Orario invariato/);
 assert.match(await page.locator('#timer-note').innerText(),/Concentrazione sospesa/);
 await page.getByRole('button',{name:'Riprendi',exact:true}).click();
 await page.getByRole('button',{name:'Concludi',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Inizia ora',exact:true}).isVisible(),true);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
} finally { await browser.close(); }
